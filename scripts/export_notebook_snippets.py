#!/usr/bin/env python3
"""Publish the notebook's code fences without its private review prose."""

import argparse
from collections import Counter
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
URL = "https://github.com/kimitaka/atcoder-library"
INITIAL_SNIPPET_COMMIT = "9aba58dbfdc2914d5d05467f24ea0e96511c29cc"
MARKER = "<!-- Generated by scripts/export_notebook_snippets.py; do not edit. -->"
SOURCE_MARKER = "Generated by scripts/export_notebook_snippets.py; do not edit."
LANGUAGES = {"haskell": "Haskell", "php": "PHP", "rust": "Rust", "python": "Python", "cpp": "C++", "javascript": "JavaScript"}
SOURCE_FILES = {"haskell": "haskell.hs", "php": "php.php", "rust": "rust.rs", "python": "python.py", "cpp": "cpp.cpp", "javascript": "javascript.js"}
COMMENTS = {"haskell": "--", "python": "#"}
FENCE = re.compile(r"^([ \t]*)(`{3,}|~{3,})(.*)$")


@dataclass
class Block:
    source: str
    index: int
    language: str
    headings: list[str]
    tab: str
    start: int
    end: int
    indent: str
    raw: list[str]
    code: str

    @property
    def citation(self):
        return f"{COMMENTS.get(self.language, '//')} Snippet source: {URL}"


def extract(source_root):
    blocks = []
    excluded = []
    originals = {}
    for path in sorted((source_root / "docs").rglob("*.md")):
        source = path.relative_to(source_root).as_posix()
        lines = path.read_text().splitlines(keepends=True)
        originals[source] = lines
        headings = []
        tab = ""
        index = 0
        i = 0
        while i < len(lines):
            line = lines[i].rstrip("\n")
            match = FENCE.match(line)
            if match:
                indent, fence, info = match.groups()
                language = info.strip().split()[0].lower() if info.strip() else ""
                end = i + 1
                while end < len(lines):
                    closing = FENCE.match(lines[end].rstrip("\n"))
                    if closing and closing[2][0] == fence[0] and len(closing[2]) >= len(fence) and not closing[3].strip():
                        break
                    end += 1
                if end == len(lines):
                    raise ValueError(f"Unclosed code fence: {source}:{i + 1}")
                if language in LANGUAGES:
                    index += 1
                    raw = lines[i + 1:end]
                    deindented = [s[len(indent):] if s.startswith(indent) else s for s in raw]
                    citation = f"{COMMENTS.get(language, '//')} Snippet source: {URL}"
                    code_lines = [s.rstrip("\n") for s in deindented if s.strip() != citation]
                    meaningful = [s for s in code_lines if s.strip() and s.strip() != "<?php" and not s.lstrip().startswith(("--", "//", "#"))]
                    if meaningful:
                        if language == "php" and (not code_lines or code_lines[0].strip() != "<?php"):
                            code_lines.insert(0, "<?php")
                        blocks.append(Block(source, index, language, [h[1] for h in headings], tab, i + 1, end, indent, raw, "\n".join(code_lines) + "\n"))
                    else:
                        excluded.append({"source": source, "index": index, "language": language, "reason": "コメントのみの空テンプレート"})
                i = end + 1
                continue
            heading = re.match(r"^(#{1,6})\s+(.+?)\s*#*\s*$", line)
            if heading:
                level, title = len(heading[1]), heading[2]
                while headings and headings[-1][0] >= level:
                    headings.pop()
                headings.append((level, title))
                tab = ""
            tab_match = re.match(r'^\s*===\s+"([^"]+)"', line)
            if tab_match:
                tab = tab_match[1]
            i += 1
    return blocks, excluded, originals


def render(blocks, excluded, notes):
    sources = {}
    entries = []
    for block in blocks:
        note = notes[block.source.removeprefix("docs/")][str(block.index)]
        kind = note["kind"]
        target = SOURCE_FILES[block.language]
        comment = COMMENTS.get(block.language, "//")
        if target not in sources:
            sources[target] = (["<?php"] if block.language == "php" else []) + [
                f"{comment} {SOURCE_MARKER}",
                block.citation,
                f"{comment} 各ブロックは独立したコード断片です。",
                f"{comment} Initial source: {URL}/tree/{INITIAL_SNIPPET_COMMIT}/snippets", "",
            ]
        original_path = block.source.removeprefix("docs/")
        anchor = f"snippet-{block.index:02d}"
        lines = sources[target]
        lines.append(f"{comment} === {original_path}#{anchor} ===")
        code_lines = block.code.splitlines()
        if block.language == "php":
            code_lines = code_lines[1:]
        start_line = len(lines) + 1
        lines.extend(code_lines)
        end_line = len(lines)
        lines.append("")
        entries.append({
            "source": block.source, "index": block.index, "language": block.language,
            "headings": block.headings, "tab": block.tab, "kind": kind, "note": note["note"],
            "code_sha256": hashlib.sha256(block.code.encode()).hexdigest(),
            "published": f"snippets/{target}#L{start_line}-L{end_line}",
            "start_line": start_line, "end_line": end_line,
            "initial_published": f"{URL}/blob/{INITIAL_SNIPPET_COMMIT}/snippets/{original_path}#{anchor}",
        })
    counts = Counter(block.language for block in blocks)
    output = {target: "\n".join(content) for target, content in sources.items()}
    output["manifest.json"] = json.dumps({"source": "atcoder-notebook/docs", "counts": dict(sorted(counts.items())), "snippets": entries, "excluded": excluded}, ensure_ascii=False, indent=2) + "\n"
    return output


def obsolete_outputs(output):
    markers = (MARKER, *(f"{comment} {SOURCE_MARKER}" for comment in ("--", "//", "#")), "<?php\n// " + SOURCE_MARKER)
    for path in sorted((ROOT / "snippets").rglob("*")):
        if path.is_file() and path.relative_to(ROOT / "snippets").as_posix() not in output:
            if path.read_text().startswith(markers):
                yield path


def check_output(output):
    for relative, expected in output.items():
        path = ROOT / "snippets" / relative
        if not path.is_file() or path.read_text() != expected:
            raise ValueError(f"Generated content differs: {path}")
    for path in obsolete_outputs(output):
        raise ValueError(f"Obsolete generated file: {path}")


def annotate_source(source_root, blocks, originals):
    grouped = {}
    for block in blocks:
        grouped.setdefault(block.source, []).append(block)
    for source, group in grouped.items():
        path = source_root / source
        lines = originals[source]
        if path.read_text() != "".join(lines):
            raise ValueError(f"Source changed during export: {source}")
        for block in reversed(group):
            raw = [s for s in block.raw if s.strip() != block.citation]
            if block.language == "php":
                if not raw or raw[0].strip() != "<?php":
                    raw.insert(0, block.indent + "<?php\n")
                offset = 1
            else:
                offset = 0
            raw.insert(offset, block.indent + block.citation + "\n")
            lines[block.start:block.end] = raw
        updated = "".join(lines)
        if path.read_text() != updated:
            path.write_text(updated)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True, help="atcoder-notebook checkout")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Check generated files without writing")
    mode.add_argument("--annotate-source", action="store_true", help="After publication, add source comments to the notebook")
    args = parser.parse_args()
    if not (args.source / "docs").is_dir():
        parser.error("--source must contain the notebook's docs directory")
    blocks, excluded, originals = extract(args.source)
    notes = json.loads(Path(__file__).with_name("notebook_notes.json").read_text())
    expected_keys = {(b.source.removeprefix("docs/"), str(b.index)) for b in blocks}
    note_keys = {(source, index) for source, entries in notes.items() for index in entries}
    if expected_keys != note_keys:
        raise ValueError(f"Update notebook_notes.json: missing={sorted(expected_keys - note_keys)}, stale={sorted(note_keys - expected_keys)}")
    output = render(blocks, excluded, notes)
    if args.check or args.annotate_source:
        check_output(output)
        if args.annotate_source:
            annotate_source(args.source, blocks, originals)
            print(f"Annotated {len(blocks)} source snippets")
    else:
        for relative, content in output.items():
            path = ROOT / "snippets" / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        for path in obsolete_outputs(output):
            path.unlink()
    print(f"{len(blocks)} snippets; {len({b.language for b in blocks})} language files; {len(excluded)} empty placeholders excluded")


if __name__ == "__main__":
    main()
