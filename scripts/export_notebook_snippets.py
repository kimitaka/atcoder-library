#!/usr/bin/env python3
"""Publish the notebook's code fences without its private review prose."""

import argparse
from collections import Counter
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
URL = "https://github.com/kimitaka/atcoder-library"
MARKER = "<!-- Generated by scripts/export_notebook_snippets.py; do not edit. -->"
LANGUAGES = {"haskell": "Haskell", "php": "PHP", "rust": "Rust", "python": "Python", "cpp": "C++", "javascript": "JavaScript"}
COMMENTS = {"haskell": "--", "python": "#"}
KINDS = {
    "program": "サンプルプログラム",
    "definitions": "関数定義（呼び出し元が必要）",
    "fragment": "コードの断片（外側の定義や文脈が必要）",
    "incomplete": "説明用の省略・未実装を含む例",
    "broken": "原文に不備があり、そのままではコンパイル不可",
}
FENCE = re.compile(r"^([ \t]*)(`{3,}|~{3,})(.*)$")


@dataclass
class Block:
    source: str
    index: int
    language: str
    headings: list[str]
    tab: str
    start: int
    end: int
    indent: str
    raw: list[str]
    code: str

    @property
    def citation(self):
        return f"{COMMENTS.get(self.language, '//')} Snippet source: {URL}"

    @property
    def annotated(self):
        lines = self.code.splitlines()
        lines.insert(1 if self.language == "php" else 0, self.citation)
        return "\n".join(lines) + "\n"


def extract(source_root):
    blocks = []
    excluded = []
    originals = {}
    for path in sorted((source_root / "docs").rglob("*.md")):
        source = path.relative_to(source_root).as_posix()
        lines = path.read_text().splitlines(keepends=True)
        originals[source] = lines
        headings = []
        tab = ""
        index = 0
        i = 0
        while i < len(lines):
            line = lines[i].rstrip("\n")
            match = FENCE.match(line)
            if match:
                indent, fence, info = match.groups()
                language = info.strip().split()[0].lower() if info.strip() else ""
                end = i + 1
                while end < len(lines):
                    closing = FENCE.match(lines[end].rstrip("\n"))
                    if closing and closing[2][0] == fence[0] and len(closing[2]) >= len(fence) and not closing[3].strip():
                        break
                    end += 1
                if end == len(lines):
                    raise ValueError(f"Unclosed code fence: {source}:{i + 1}")
                if language in LANGUAGES:
                    index += 1
                    raw = lines[i + 1:end]
                    deindented = [s[len(indent):] if s.startswith(indent) else s for s in raw]
                    citation = f"{COMMENTS.get(language, '//')} Snippet source: {URL}"
                    code_lines = [s.rstrip("\n") for s in deindented if s.strip() != citation]
                    meaningful = [s for s in code_lines if s.strip() and s.strip() != "<?php" and not s.lstrip().startswith(("--", "//", "#"))]
                    if meaningful:
                        if language == "php" and (not code_lines or code_lines[0].strip() != "<?php"):
                            code_lines.insert(0, "<?php")
                        blocks.append(Block(source, index, language, [h[1] for h in headings], tab, i + 1, end, indent, raw, "\n".join(code_lines) + "\n"))
                    else:
                        excluded.append({"source": source, "index": index, "language": language, "reason": "コメントのみの空テンプレート"})
                i = end + 1
                continue
            heading = re.match(r"^(#{1,6})\s+(.+?)\s*#*\s*$", line)
            if heading:
                level, title = len(heading[1]), heading[2]
                while headings and headings[-1][0] >= level:
                    headings.pop()
                headings.append((level, title))
                tab = ""
            tab_match = re.match(r'^\s*===\s+"([^"]+)"', line)
            if tab_match:
                tab = tab_match[1]
            i += 1
    return blocks, excluded, originals


def render(blocks, excluded, notes):
    pages = {}
    entries = []
    for block in blocks:
        note = notes[block.source.removeprefix("docs/")][str(block.index)]
        kind = note["kind"]
        label = KINDS[kind]
        target = block.source.removeprefix("docs/")
        if target not in pages:
            pages[target] = [MARKER, "", f"# {block.headings[0]}", "", f"元ノート: `{block.source}`", "", "[スニペット索引へ](" + "../" * (len(Path(target).parts) - 1) + "README.md)", "", "コードの処理は原文のままです。出典コメントとPHP開始タグを補っています。各例は個別に参照し、区分・前提を確認してください。", ""]
        heading = " → ".join(block.headings[1:]) or block.headings[0]
        if block.tab and block.tab not in LANGUAGES.values():
            heading += f" → {block.tab}"
        anchor = f"snippet-{block.index:02d}"
        pages[target].extend([f'<a id="{anchor}"></a>', "", f"## Snippet {block.index:02d} — {LANGUAGES[block.language]}", "", f"元の見出し: {heading}", "", f"区分: {label}", ""])
        if note["note"]:
            pages[target].extend([note["note"], ""])
        fence = "`" * max(3, max((len(s) + 1 for s in re.findall(r"`+", block.annotated)), default=3))
        pages[target].extend([fence + block.language, block.annotated.rstrip("\n"), fence, ""])
        entries.append({"source": block.source, "index": block.index, "language": block.language, "headings": block.headings, "tab": block.tab, "kind": kind, "note": note["note"], "code_sha256": hashlib.sha256(block.code.encode()).hexdigest(), "published": f"snippets/{target}#{anchor}"})
    counts = Counter(block.language for block in blocks)
    index = [MARKER, "", "# atcoder-notebook のコードスニペット", "", f"{len(pages)}ページ・{len(blocks)}件（" + "、".join(f"{LANGUAGES[language]} {count}件" for language, count in sorted(counts.items())) + "）を公開しています。", "", "元ノートのコードと見出しを抽出しています。振り返りの本文、入力例、Mermaid図、コメントだけの空テンプレートは含めていません。", "", "| ページ | Haskell | PHP |", "| --- | ---: | ---: |"]
    for target in pages:
        page_blocks = [b for b in blocks if b.source == "docs/" + target]
        count = Counter(b.language for b in page_blocks)
        index.append(f"| [{page_blocks[0].headings[0]}]({target}) | {count['haskell']} | {count['php']} |")
    index.extend(["", "## コピーして使うとき", "", "コード内の `Snippet source:` コメントを提出ソースにも残してください。すでに同じリポジトリの `Template source:` コメントがあれば、参照URLを重複して記載する必要はありません。", "", "スニペットには関数定義・式・`do` 内の断片・省略例も含まれます。単独で実行できるとは限りません。既知の不備や依存関係は各ブロックの前に記載しています。", "", "HaskellのBFSと高速I/Oの骨組みは原文にコンパイルできない箇所があります。PHPの等比和は別途 `pow_mod`・`inv_mod` が必要です。公開対象の原文を残すため、これらの処理は修正していません。", "", "## 更新", "", "リポジトリのルートで次を実行します。標準ライブラリのみのPython 3.10以降を使います。", "", "```sh", "python3 scripts/export_notebook_snippets.py --source ../atcoder-notebook", "python3 scripts/export_notebook_snippets.py --source ../atcoder-notebook --check", "```", "", "追加・変更時は `scripts/notebook_notes.json` の区分と注記も確認してください。差分を確認し、使用するコンテストの開始前にpushしてください。", "", "公開後、元ノート内のコードにも参照URLを反映できます。コードの処理やノート本文は変更しません。", "", "```sh", "python3 scripts/export_notebook_snippets.py --source ../atcoder-notebook --annotate-source", "```", "", "各ブロックの元ファイル・順序・正規化後コードのSHA-256は [manifest.json](manifest.json) に記録しています。PHP開始タグを補い、出典コメントを除いたコードをハッシュ化します。", ""])
    output = {target: "\n".join(content) for target, content in pages.items()}
    output["README.md"] = "\n".join(index)
    output["manifest.json"] = json.dumps({"source": "atcoder-notebook/docs", "counts": dict(sorted(counts.items())), "snippets": entries, "excluded": excluded}, ensure_ascii=False, indent=2) + "\n"
    return output


def check_output(output):
    for relative, expected in output.items():
        path = ROOT / "snippets" / relative
        if not path.is_file() or path.read_text() != expected:
            raise ValueError(f"Generated content differs: {path}")


def annotate_source(source_root, blocks, originals):
    grouped = {}
    for block in blocks:
        grouped.setdefault(block.source, []).append(block)
    for source, group in grouped.items():
        path = source_root / source
        lines = originals[source]
        if path.read_text() != "".join(lines):
            raise ValueError(f"Source changed during export: {source}")
        for block in reversed(group):
            raw = [s for s in block.raw if s.strip() != block.citation]
            if block.language == "php":
                if not raw or raw[0].strip() != "<?php":
                    raw.insert(0, block.indent + "<?php\n")
                offset = 1
            else:
                offset = 0
            raw.insert(offset, block.indent + block.citation + "\n")
            lines[block.start:block.end] = raw
        updated = "".join(lines)
        if path.read_text() != updated:
            path.write_text(updated)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True, help="atcoder-notebook checkout")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Check generated files without writing")
    mode.add_argument("--annotate-source", action="store_true", help="After publication, add source comments to the notebook")
    args = parser.parse_args()
    if not (args.source / "docs").is_dir():
        parser.error("--source must contain the notebook's docs directory")
    blocks, excluded, originals = extract(args.source)
    notes = json.loads(Path(__file__).with_name("notebook_notes.json").read_text())
    expected_keys = {(b.source.removeprefix("docs/"), str(b.index)) for b in blocks}
    note_keys = {(source, index) for source, entries in notes.items() for index in entries}
    if expected_keys != note_keys:
        raise ValueError(f"Update notebook_notes.json: missing={sorted(expected_keys - note_keys)}, stale={sorted(note_keys - expected_keys)}")
    output = render(blocks, excluded, notes)
    if args.check or args.annotate_source:
        check_output(output)
        if args.annotate_source:
            annotate_source(args.source, blocks, originals)
            print(f"Annotated {len(blocks)} source snippets")
    else:
        for relative, content in output.items():
            path = ROOT / "snippets" / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        for path in (ROOT / "snippets").rglob("*.md"):
            if path.relative_to(ROOT / "snippets").as_posix() not in output and path.read_text().startswith(MARKER):
                path.unlink()
    print(f"{len(blocks)} snippets; {len({b.source for b in blocks})} pages; {len(excluded)} empty placeholders excluded")


if __name__ == "__main__":
    main()
